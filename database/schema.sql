-- Esquema PostgreSQL para la migracion del sistema de farmacia.
-- Primero crea la base de datos farmacia y luego ejecuta este archivo
-- conectado a dicha base de datos.

BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (BTRIM(nombre) <> ''),
    correo VARCHAR(254) NOT NULL UNIQUE
        CHECK (BTRIM(correo) <> '' AND correo = LOWER(BTRIM(correo))),
    password_hash TEXT NOT NULL CHECK (BTRIM(password_hash) <> ''),
    rol VARCHAR(20) NOT NULL
        CHECK (rol IN ('administrador', 'operador', 'consulta', 'auditor')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS medicamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE CHECK (BTRIM(codigo) <> ''),
    nombre VARCHAR(150) NOT NULL CHECK (BTRIM(nombre) <> ''),
    principio_activo VARCHAR(150) NOT NULL CHECK (BTRIM(principio_activo) <> ''),
    presentacion VARCHAR(120) NOT NULL CHECK (BTRIM(presentacion) <> ''),
    requiere_formula BOOLEAN NOT NULL DEFAULT FALSE,
    precio_referencia NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (precio_referencia >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_id BIGINT NOT NULL,
    codigo_lote VARCHAR(80) NOT NULL CHECK (BTRIM(codigo_lote) <> ''),
    fecha_vencimiento DATE NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    costo_unitario NUMERIC(12, 2) NOT NULL CHECK (costo_unitario >= 0),
    precio_venta NUMERIC(12, 2) NOT NULL CHECK (precio_venta >= 0),
    CONSTRAINT uq_lotes_medicamento_codigo
        UNIQUE (medicamento_id, codigo_lote),
    CONSTRAINT fk_lotes_medicamento
        FOREIGN KEY (medicamento_id) REFERENCES medicamentos (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(40) NOT NULL UNIQUE CHECK (BTRIM(numero) <> ''),
    usuario_id BIGINT NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    estado VARCHAR(12) NOT NULL DEFAULT 'confirmada'
        CHECK (estado IN ('confirmada', 'revertida')),
    CONSTRAINT fk_ventas_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL,
    lote_id BIGINT NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT ck_detalle_venta_subtotal
        CHECK (subtotal = ROUND(cantidad * precio_unitario, 2)),
    CONSTRAINT uq_detalle_venta_lote UNIQUE (venta_id, lote_id),
    CONSTRAINT fk_detalle_venta_venta
        FOREIGN KEY (venta_id) REFERENCES ventas (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_venta_lote
        FOREIGN KEY (lote_id) REFERENCES lotes (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    venta_id BIGINT,
    usuario_id BIGINT NOT NULL,
    tipo VARCHAR(12) NOT NULL
        CHECK (tipo IN ('entrada', 'salida', 'ajuste', 'reversión')),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    stock_antes INTEGER NOT NULL CHECK (stock_antes >= 0),
    stock_despues INTEGER NOT NULL CHECK (stock_despues >= 0),
    motivo VARCHAR(300) NOT NULL CHECK (BTRIM(motivo) <> ''),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventario_stock_movimiento CHECK (
        (tipo = 'entrada' AND stock_despues = stock_antes + cantidad)
        OR (tipo = 'salida' AND cantidad <= stock_antes
            AND stock_despues = stock_antes - cantidad)
        OR (tipo = 'reversión' AND stock_despues = stock_antes + cantidad)
        OR (tipo = 'ajuste'
            AND cantidad = ABS(stock_despues - stock_antes))
    ),
    CONSTRAINT fk_inventario_lote
        FOREIGN KEY (lote_id) REFERENCES lotes (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventario_venta
        FOREIGN KEY (venta_id) REFERENCES ventas (id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventario_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol_activo
    ON usuarios (rol, activo);
CREATE INDEX IF NOT EXISTS idx_medicamentos_nombre
    ON medicamentos (nombre);
CREATE INDEX IF NOT EXISTS idx_medicamentos_principio_activo
    ON medicamentos (principio_activo);
CREATE INDEX IF NOT EXISTS idx_lotes_vencimiento
    ON lotes (fecha_vencimiento);
CREATE INDEX IF NOT EXISTS idx_lotes_medicamento_vencimiento
    ON lotes (medicamento_id, fecha_vencimiento);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha
    ON ventas (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_ventas_usuario_fecha
    ON ventas (usuario_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_detalle_venta_lote
    ON detalle_venta (lote_id);
CREATE INDEX IF NOT EXISTS idx_inventario_lote_fecha
    ON inventario (lote_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_inventario_venta_fecha
    ON inventario (venta_id, fecha DESC)
    WHERE venta_id IS NOT NULL;

COMMIT;
